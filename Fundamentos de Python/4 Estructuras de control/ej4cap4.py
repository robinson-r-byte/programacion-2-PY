#4. Escribe un programa que use un ciclo while para pedir al usuario una contraseña.
#El programa debe seguir pidiendo hasta que el usuario escriba la contraseña correcta
#(por ejemplo, “python123”).

contaseña = input("Ingrese la contraseña:") 

while contaseña !=  "python123" :
    print("contraseña incorrecta:")
    contaseña = input("Ingrese la contraseña:") 

